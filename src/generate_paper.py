# STYLE SETUP
# =============================================================================
def get_styles():
    styles = getSampleStyleSheet()
    
    # Title
    styles.add(ParagraphStyle(
        name='PaperTitle',
        parent=styles['Title'],
        fontName='Times-Roman',
        fontSize=18,
        leading=22,
        alignment=TA_CENTER,
        spaceAfter=12
    ))
    
    # Author
    styles.add(ParagraphStyle(
        name='Author',
        parent=styles['Normal'],
        fontName='Times-Roman',
        fontSize=12,
        alignment=TA_CENTER,
        spaceAfter=6
    ))
    
    # Date
    styles.add(ParagraphStyle(
        name='DateLine',
        parent=styles['Normal'],
        fontName='Times-Roman',
        fontSize=10,
        alignment=TA_CENTER,
        spaceAfter=24,
        textColor=colors.grey
    ))
    
    # Abstract
    styles.add(ParagraphStyle(
        name='Abstract',
        parent=styles['Normal'],
        fontName='Times-Roman',
        fontSize=11,
        leading=14,
        spaceAfter=12,
        alignment=TA_JUSTIFY
    ))
    
    # Section Heading
    styles.add(ParagraphStyle(
        name='SectionHeading',
        parent=styles['Heading2'],
        fontName='Times-Bold',
        fontSize=13,
        spaceAfter=10,
        spaceBefore=14
    ))
    
    # Subsection Heading
    styles.add(ParagraphStyle(
        name='SubHeading',
        parent=styles['Heading3'],
        fontName='Times-Bold',
        fontSize=11,
        spaceAfter=6,
        spaceBefore=8
    ))
    
    # Body Text (renamed to PaperBody to avoid conflict)
    styles.add(ParagraphStyle(
        name='PaperBody',
        parent=styles['Normal'],
        fontName='Times-Roman',
        fontSize=11,
        leading=14,
        spaceAfter=6,
        alignment=TA_JUSTIFY
    ))
    
    # Caption
    styles.add(ParagraphStyle(
        name='Caption',
        parent=styles['Normal'],
        fontName='Times-Roman',
        fontSize=9,
        leading=11,
        alignment=TA_CENTER,
        spaceAfter=10
    ))
    
    # Table Header
    styles.add(ParagraphStyle(
        name='TableHeader',
        parent=styles['Normal'],
        fontName='Times-Bold',
        fontSize=10,
        alignment=TA_CENTER
    ))
    
    # Table Cell
    styles.add(ParagraphStyle(
        name='TableCell',
        parent=styles['Normal'],
        fontName='Times-Roman',
        fontSize=9,
        alignment=TA_CENTER
    ))
    
    return styles


